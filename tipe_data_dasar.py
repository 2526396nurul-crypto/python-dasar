# Integer
jumlah_pensil = 8
print(jumlah_pensil, type(jumlah_pensil))

# Float
suhu = 29.5
print(suhu, type(suhu))

# String
nama = "Nurul"
print(nama, type(nama))

# Boolean
is_active = True
print(is_active, type(is_active))

# List
buah = ["salak", "jambu", "pisang"]
print(buah, type(buah))

# Tuple
warna = ("kuning", "ungu", "hitam")
print(warna, type(warna))

# Dictionary
siswa = {"nama": "Nurul", "sekolah": "SMKN 2 Subang", "kota": "Subang"}
print(siswa, type(siswa))

# Set
angka = {4, 4, 5, 5, 6}
print(angka, type(angka))
